import type { Preview } from "@storybook/angular";
import { componentWrapperDecorator, moduleMetadata } from "@storybook/angular";
import { setCompodocJson } from "@storybook/addon-docs/angular";
import docJson from "../documentation.json";
import { StorybookThemeSyncComponent } from "./storybook-theme-sync.component";
import { StorybookLayerWrapperComponent } from "./storybook-layer-wrapper.component";
import { RecursicaJsonService } from "../src/storybook-demos/recursica-json.service";
import recursicaTheme from "./RecursicaTheme";
// Real Recursica design-token CSS custom properties (repo root, generated by
// Forge — see docs/CREATING_AN_ADAPTER.md step 5's "Install Recursica JSON
// and CSS from Forge" note) are wired in via `angular.json`'s
// `storybook`/`build-storybook` architect targets' own `styles` array, not a
// plain import here — see angular.json for why and this repo's
// theme-provider/IMPLEMENTATION_NOTES.md for the full verification writeup.
// A bare `import "../../../recursica_variables_scoped.css"` here fails: this
// file has no loader for a plain top-level CSS import (Storybook's Angular
// webpack config only wires up css-loader/style-loader for CSS reachable
// through Angular's own `styles`-array build pipeline, confirmed by reading
// `@storybook/angular/dist/server/framework-preset-angular-cli.js` and by
// actually trying the plain-import approach first and getting
// "Module parse failed... no loaders are configured" for the .css file).
setCompodocJson(docJson);

// Real Google Fonts loading (docs/CREATING_AN_ADAPTER.md-style rationale:
// direct port of `@recursica/storybook-template`'s `withRecursicaFonts`
// decorator, read out of that package's compiled `dist/preview-*.js` bundle
// since it ships no readable source for a Vite-only React project — see
// `RecursicaJsonService.loadGoogleFonts()`'s own doc comment). The source
// applies this as a global decorator (`createPreviewConfig`), i.e. once per
// Storybook preview, to every story, not just the token/font demo stories
// under `src/storybook-demos/` — invoking it here, once, at preview
// module-init time, is the direct equivalent: real `<link rel="stylesheet">`
// tags for every typeface in `tokens.font.typefaces` land in `document.head`
// before any story renders, so the `Tokens/Font/*` demos (and anything else
// that happens to use these families) render in the real webfonts instead of
// falling back to system fonts. `RecursicaJsonService` itself doesn't need
// Angular's DI container for this call (no injected dependencies of its
// own), and its `document.head` de-duplication check makes a second,
// independently-constructed instance calling this again elsewhere
// (e.g. Angular's own DI-provided singleton) harmless.
new RecursicaJsonService().loadGoogleFonts();

const preview: Preview = {
  // Ports the reference's own global `layer`/`withLayer` Storybook args
  // (`recursica-adapter-mantine-v8/.storybook/preview.tsx`) — every story
  // in this Storybook renders wrapped in a `rec-layer` by default (layer 0),
  // with per-story Controls-panel overrides. See
  // `storybook-layer-wrapper.component.ts`'s own header comment for the
  // full port writeup.
  args: {
    withLayer: true,
    layer: 0,
  },
  argTypes: {
    withLayer: {
      control: "boolean",
      description:
        "Wrap this story dynamically in a Recursica design-system Layer?",
      table: { category: "Story Controls" },
    },
    layer: {
      control: "inline-radio",
      options: [0, 1, 2, 3],
      description:
        "Dynamically tests the recursive variable mappings across underlying design-system layers.",
      table: { category: "Story Controls" },
      if: { arg: "withLayer", truthy: true },
    },
  },
  parameters: {
    controls: {
      matchers: {
        color: /(background|color)$/i,
        date: /Date$/i,
      },
    },
    // Cosmetic Storybook manager-UI (chrome) theming. Ported as-is from the
    // React reference adapter's own `darkMode` parameter — currently inert
    // (nothing reads it; it was written for the `storybook-dark-mode`
    // addon's own sidebar/toolbar styling, which isn't registered here, see
    // `main.ts`), left configured and harmless in case a future addon or
    // Storybook feature consumes it.
    darkMode: {
      current: "light",
      dark: recursicaTheme,
      light: recursicaTheme,
    },
  },
  // Storybook's own native toolbar mechanism (no addon required) — adds the
  // actual light/dark toggle button to Storybook's toolbar. See
  // `storybook-theme-sync.component.ts`'s header comment for why this
  // replaces the (broken, for this Storybook version) `storybook-dark-mode`
  // addon the React reference adapter uses.
  globalTypes: {
    theme: {
      description: "Recursica theme",
      toolbar: {
        title: "Theme",
        icon: "circlehollow",
        items: [
          { value: "light", icon: "sun", title: "Light" },
          { value: "dark", icon: "moon", title: "Dark" },
        ],
        dynamicTitle: true,
      },
    },
  },
  initialGlobals: {
    theme: "light",
  },
  // Global decorator, applied to every story in this Storybook instance —
  // wraps each story's rendered content in `StorybookThemeSyncComponent`,
  // which forwards the toolbar's currently-selected theme (read from
  // `storyContext.globals["theme"]` above) to the real `ThemeProviderComponent`
  // (`rec-theme-provider`). See `storybook-theme-sync.component.ts`'s own
  // header comment for the full rationale, including how/why this differs
  // from and improves on the React reference adapter's `ColorSchemeWrapper`.
  decorators: [
    moduleMetadata({
      imports: [StorybookThemeSyncComponent, StorybookLayerWrapperComponent],
    }),
    componentWrapperDecorator(StorybookThemeSyncComponent, (context) => ({
      theme:
        (context.globals["theme"] as "light" | "dark" | undefined) ?? "light",
    })),
    // Nested inside the theme-sync decorator above (theme provisioning has
    // to be outermost so `rec-layer`'s own theme+layer-scoped color tokens
    // resolve) — matches the reference's own `MantineProvider >
    // ColorSchemeWrapper > Layer` nesting order.
    componentWrapperDecorator(StorybookLayerWrapperComponent, (context) => ({
      withLayer: (context.args["withLayer"] as boolean | undefined) ?? true,
      layer: (context.args["layer"] as 0 | 1 | 2 | 3 | undefined) ?? 0,
    })),
  ],
};

export default preview;
